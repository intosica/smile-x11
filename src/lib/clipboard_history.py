"""Clipboard history store (text only). In memory by default; on-disk persistence is opt-in.

This module never touches the system clipboard: ClipboardPage feeds it text it *read* from the clipboard.
"""
import json
import os
import time

from gi.repository import GLib

MAX_ENTRIES = 50          # unpinned entries; pins are never evicted
MAX_LENGTH = 10000        # longer clips are ignored
# MIME types / flags set by password managers and other apps to mark a clip as secret
SENSITIVE_MIME_TYPES = (
    'x-kde-passwordManagerHint',
    'application/x-kde-passwordManagerHint',
    'org.nspasteboard.ConcealedType',
    'org.nspasteboard.TransientType',
    'org.nspasteboard.AutoGeneratedType',
    'x-gnome-secret',
    'application/x-gnome-keyring-secret',
)


def history_path() -> str:
    return os.path.join(GLib.get_user_data_dir(), 'smile-panel', 'clipboard_history.json')


class ClipboardHistory:
    def __init__(self, persist: bool = False):
        self.entries: list[dict] = []  # newest first: {'text', 'pinned', 'time'}
        self.persist = persist
        if persist:
            self._load()

    def add(self, text: str) -> bool:
        if not text.strip() or len(text) > MAX_LENGTH:
            return False
        existing = next((e for e in self.entries if e['text'] == text), None)
        if existing:
            self.entries.remove(existing)
            existing['time'] = time.time()
            self.entries.insert(0, existing)
        else:
            self.entries.insert(0, {'text': text, 'pinned': False, 'time': time.time()})
        unpinned = [e for e in self.entries if not e['pinned']]
        for old in unpinned[MAX_ENTRIES:]:
            self.entries.remove(old)
        self._save()
        return True

    def toggle_pin(self, text: str):
        for e in self.entries:
            if e['text'] == text:
                e['pinned'] = not e['pinned']
        self._save()

    def remove(self, text: str):
        self.entries = [e for e in self.entries if e['text'] != text]
        self._save()

    def clear_unpinned(self):
        self.entries = [e for e in self.entries if e['pinned']]
        self._save()

    def ordered(self) -> list[dict]:
        """Pinned entries first, then by recency."""
        return [e for e in self.entries if e['pinned']] + [e for e in self.entries if not e['pinned']]

    def set_persist(self, persist: bool):
        self.persist = persist
        if persist:
            self._save()
        else:
            self.delete_file()

    @staticmethod
    def delete_file():
        try:
            os.remove(history_path())
        except FileNotFoundError:
            pass

    def _load(self):
        try:
            with open(history_path(), encoding='utf-8') as f:
                data = json.load(f)
            self.entries = [{'text': str(e['text']), 'pinned': bool(e.get('pinned')), 'time': float(e.get('time', 0))}
                            for e in data if isinstance(e, dict) and e.get('text')]
        except (OSError, ValueError, KeyError, TypeError):
            self.entries = []

    def _save(self):
        if not self.persist:
            return
        path = history_path()
        os.makedirs(os.path.dirname(path), mode=0o700, exist_ok=True)
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, 'w', encoding='utf-8') as f:
            json.dump(self.entries, f)
        os.chmod(path, 0o600)


_display = None


def clipboard_marked_sensitive() -> bool:
    """True if the current CLIPBOARD owner flags its selection as a secret (KDE/x-kde-passwordManagerHint)."""
    global _display
    try:
        if _display is None:
            import Xlib.display

            _display = Xlib.display.Display()
        owner = _display.get_selection_owner(_display.intern_atom('CLIPBOARD'))
        if not owner:
            return False
        prop = owner.get_full_property(_display.intern_atom('x-kde-passwordManagerHint'), Xlib.X.AnyPropertyType)
        return bool(prop and prop.value and prop.value[0])
    except Exception:
        return False
